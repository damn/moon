(ns clojure.com.badlogic.gdx.scenes.scene2d.ui.text-field
  "A single-line text input field.
  
  The preferred height of a text field is the height of the font and background.
  The preferred width of a text field is 150, a relatively arbitrary size.
  
  The text field will copy the currently selected text when ctrl+c is pressed, and paste any text in the clipboard when ctrl+v is
  pressed. Clipboard functionality is provided via the clipboard interface. Currently there are two standard
  implementations, one for the desktop and one for Android. The Android clipboard is a stub, as copy & pasting on Android is not
  supported yet.
  
  The text field allows you to specify an onscreen keyboard for displaying a softkeyboard and piping all key events
  generated by the keyboard to the text field. There are two standard implementations, one for the desktop and one for Android.
  The desktop keyboard is a stub, as a softkeyboard is not needed on the desktop. The Android onscreen keyboard
  implementation will bring up the default IME."
  (:import (com.badlogic.gdx.scenes.scene2d.ui Skin TextField)))

(defn create [^String text ^Skin skin]
  (TextField. text skin))

(defn text
  "Returns never null, might be an empty string."
  [^TextField text-field]
  (.getText text-field))
