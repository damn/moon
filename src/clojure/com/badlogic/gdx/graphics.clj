(ns clojure.com.badlogic.gdx.graphics
  "This interface encapsulates communication with the graphics processor. Depending on the available hardware and the current
  application configuration, access to gl20 and gl30 are provided here.
  
  If supported by the backend, this interface lets you query the available display modes (graphics resolution and color depth)
  and change it.
  
  This interface can be used to switch between continuous and non-continuous rendering (see
  set continuous rendering), and to explicitly request rendering.
  
  There are many more utility classes that are not directly generated by the this namespace interfaces. See vertex array
  , vertex buffer object, index buffer object, mesh, shader program and frame buffer,
  [[clojure.com.badlogic.gdx.graphics.g2d.bitmap-font]], [[clojure.com.badlogic.gdx.graphics.g2d.batch]] and so on. All these classes are managed, meaning they don't need to be reloaded on a context
  loss. Explore the graphics package for more classes that might come in handy."
  (:import (com.badlogic.gdx Graphics)
           (com.badlogic.gdx.graphics Cursor Pixmap)))

(defn new-cursor
  "Create a new cursor represented by the [[clojure.com.badlogic.gdx.graphics.pixmap]]. The Pixmap must be in RGBA8888 format,
  width & height must be powers-of-two greater than zero (not necessarily equal) and of a certain minimum size (32x32 is a
  safe bet), and alpha transparency must be single-bit (i.e., 0x00 or 0xFF only). This function returns a Cursor object that
  can be set as the system cursor by calling [set-cursor!] .
  
  - `pixmap`: the mouse cursor image as a [[clojure.com.badlogic.gdx.graphics.pixmap]]
  
  Returns a cursor object that can be used by calling [set-cursor!] or null if not supported"
  [^Graphics graphics ^Pixmap pixmap hotspot-x hotspot-y]
  (.newCursor graphics pixmap hotspot-x hotspot-y))

(defn delta-time
  "Returns the time span between the current frame and the last frame in seconds."
  [^Graphics graphics]
  (.getDeltaTime graphics))

(defn frames-per-second
  "Returns the average number of frames per second"
  [^Graphics graphics]
  (.getFramesPerSecond graphics))

(defn set-cursor!
  "Only viable on the lwjgl-backend and on the gwt-backend. Browsers that support cursor:url() and support the png format (the
  pixmap is converted to a data-url of type image/png) should also support custom cursors. Will set the mouse cursor image to
  the image represented by the cursor. It is recommended to call this function in the main
  render thread, and maximum one time per frame.
  
  - `cursor`: the mouse cursor as a cursor"
  [^Graphics graphics cursor]
  (.setCursor graphics cursor))
